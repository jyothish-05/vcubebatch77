package com.arrays;

public class Chararr {

	public static void main(String[] args) {
		
		char symbol[] = new char[5];
		
		symbol[0] = '!';
		symbol[1] = '@';
		symbol[2] = '#';
		symbol[3] = '$';
		symbol[4] = '%';
		
		for(int i = 0;i<symbol.length;i++) {
			System.out.println(symbol[i]);
		}
		

	}

}
